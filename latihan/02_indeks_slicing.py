# Latihan 2: Indeks dan Slicing
# Menampilkan elemen pertama, terakhir, tiga elemen awal,
# serta elemen pada indeks 1 sampai 3 (indeks akhir tidak disertakan).

nilai = [75, 80, 65, 90, 88, 70]

print("Elemen pertama:", nilai[0])
print("Elemen terakhir:", nilai[-1])
print("Tiga elemen awal:", nilai[:3])
print("Indeks 1 sampai 3:", nilai[1:4])
